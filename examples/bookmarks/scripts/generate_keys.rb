#!/usr/bin/env ruby
# frozen_string_literal: true

require 'jose'
require 'json'

key = JOSE::JWK.generate_key([:ec, "P-256"])
key_id = "key-#{Time.now.to_i}"

private_jwk = key.to_map.to_h.merge("kid" => key_id, "use" => "sig")
public_jwk = key.to_public_map.to_h.merge("kid" => key_id, "use" => "sig")

puts "=" * 40
puts "PRIVATE KEY".center(40)
puts "=" * 40

puts
puts "Copy this JSON into config/keys.json. The key object should be passed as the `singing_key` to the " +
  "`AuthProto::Client` initializer. It must NOT be accessible publicly."
puts

puts JSON.pretty_generate('keys' => [private_jwk])
puts

puts "=" * 40
puts "PUBLIC KEY".center(40)
puts "=" * 40

puts
puts "Copy this JSON into config/oauth-client-metadata.json. This is a public key read by the authorization " +
  "server so that it can validate the client assertions generated by your app."
puts

puts JSON.pretty_generate('jwks' => { 'keys' => [public_jwk] })
puts
